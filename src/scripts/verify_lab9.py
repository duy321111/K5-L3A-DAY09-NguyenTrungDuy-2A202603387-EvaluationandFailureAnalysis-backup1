"""Reproduce M0-M7 evidence. Run from src: python scripts/verify_lab9.py.

Expected failures (helpful judge, seeded regression and each trap) must return 1.
Evidence is generated by commands, never patched into JSON reports.
"""
from __future__ import annotations
import argparse
from datetime import datetime
from pathlib import Path
import os
import subprocess
import sys
import tempfile
import json


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--reuse-reports", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    os.chdir(root)
    logdir = root / "reports/verification"
    logdir.mkdir(parents=True, exist_ok=True)
    entries = []
    def run(name, argv, expected=0):
        result = subprocess.run([sys.executable, *argv], capture_output=True, text=True,
                                encoding="utf-8", env={**os.environ, "PYTHONUTF8":"1"})
        output = result.stdout + result.stderr
        (logdir / f"{name}.txt").write_text(output, encoding="utf-8")
        passed = result.returncode == expected
        entries.append(dict(name=name, command=[sys.executable,*argv], expected=expected,
                            exit_code=result.returncode, passed=passed))
        print(f"{name}: exit {result.returncode}, expected {expected} - {'PASS' if passed else 'FAIL'}", flush=True)
        if not passed:
            print(output[-5000:], flush=True)
        return result
    run("m0_smoke", ["-m","lab9.smoke"])
    run("m1_evalset", ["-m","lab9.evalset","--check"])
    run("m5_cross_principal", ["-m","lab9.trace_case","--shape","fixed","--claim","C-110","--seed","11","--spec","config/metric_spec_v2.yaml"])
    run("m5_evalset", ["-m","lab9.evalset","--v2","--check"])
    run("m2_tone", ["-m","lab9.judge","--csv","data/eval/judge_tone_public.csv","--audit","10"])
    run("m2_helpful", ["-m","lab9.judge","--csv","data/eval/judge_helpful_public.csv","--audit","5"], 1)
    with tempfile.TemporaryDirectory(prefix="lab9-verify-tests-") as tmp:
        run("tests_lab9", ["-m","pytest","-q","-o","addopts=","-p","no:cacheprovider","--basetemp",str(Path(tmp)/'cases'),"-k","lab9"])
    with tempfile.TemporaryDirectory(prefix="lab9-verify-host-") as tmp:
        run("tests_host", ["-m","pytest","-q","-p","no:cacheprovider","--basetemp",str(Path(tmp)/'cases')])
    for shape, filename in [("swarm","baseline_v1"),("fixed","eval_fixed"),("seeded_regression","eval_seeded_regression")]:
        if not args.reuse_reports or not Path(f"reports/{filename}.json").is_file():
            run(filename, ["-m","lab9.eval","--shape",shape,"--out",f"reports/{filename}.json"])
    if not args.reuse_reports or not Path("reports/baseline_v2.json").is_file():
        run("baseline_v2", ["-m","lab9.eval","--shape","swarm","--spec","config/metric_spec_v2.yaml","--out","reports/baseline_v2.json"])
    run("m4_eval_pr", ["-m","lab9.eval","--shape","swarm","--out","reports/eval_pr.json"])
    run("m4_baseline_check", ["-m","lab9.ci_check","--pr","reports/eval_pr.json","--baseline","reports/baseline_v1.json"])
    for name, expected in [("pr",0),("fixed",0),("seeded_regression",1)]:
        run(f"m4_gate_{name}", ["-m","lab9.gate","--pr",f"reports/eval_{name}.json","--baseline","reports/baseline_v1.json"], expected)
    run("m3_detection", ["-m","lab9.mutation","--detect"])
    run("m6_aa", ["-m","lab9.mutation","--spec","config/metric_spec_v2.yaml","--aa","66,77,88,99,110"])
    run("m5_m7_scorecard", ["-m","lab9.mutation","--spec","config/metric_spec_v2.yaml","--baseline","reports/baseline_v2.json"])
    run("m7_slice_report", ["-m","lab9.eval","--shape","slice_regression","--spec","config/metric_spec_v2.yaml","--out","reports/eval_slice_regression.json"])
    run("m7_traps", ["-m","lab9.traps","--pr","reports/eval_slice_regression.json","--baseline","reports/baseline_v2.json","--spec","config/metric_spec_v2.yaml"])
    for name in ["evaluator_errors_as_nan","dropped_failing_rows","cherry_picked_seeds","loosened_spec"]:
        cmd = ["-m","lab9.gate","--pr",f"reports/traps/{name}.json","--baseline","reports/baseline_v2.json"]
        if name == "loosened_spec":
            cmd += ["--spec",f"reports/traps/{name}.spec.yaml","--base-spec","config/metric_spec_v2.yaml"]
        else:
            cmd += ["--spec","config/metric_spec_v2.yaml"]
        run(f"m7_gate_{name}", cmd, 1)
    summary = dict(passed=all(e['passed'] for e in entries), checks=entries)
    (logdir/'summary.json').write_text(json.dumps(summary,indent=2),encoding='utf-8')
    print(f"Verification: {sum(e['passed'] for e in entries)}/{len(entries)} expected outcomes",flush=True)
    return 0 if summary['passed'] else 1


if __name__ == "__main__":
    raise SystemExit(main())
